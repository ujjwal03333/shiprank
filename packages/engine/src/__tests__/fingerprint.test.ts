// ── Model inference — spec confidence table ───────────────────────────────────

describe("inferModel — confidence table", () => {
  function detect(platform: string, confidence = 90) {
    return inferModel({ platform: platform as never, confidence, signals: ["test"] });
  }

  it("lovable → claude-sonnet-4-6 (conf 80)", () => {
    const m = detect("lovable");
    expect(m.model).toBe("claude-sonnet-4-6");
    expect(m.confidence).toBe(80);
  });

  it("bolt → claude-opus-4-8 (conf 75)", () => {
    const m = detect("bolt");
    expect(m.model).toBe("claude-opus-4-8");
    expect(m.confidence).toBe(75);
  });

  it("cursor → claude-opus-4-8 (conf 55 — user-chosen, lower)", () => {
    const m = detect("cursor");
    expect(m.model).toBe("claude-opus-4-8");
    expect(m.confidence).toBe(55);
  });

  it("v0 → gpt-5.5 (conf 70)", () => {
    const m = detect("v0");
    expect(m.model).toBe("gpt-5.5");
    expect(m.confidence).toBe(70);
  });

  it("replit → gpt-4o (conf 60)", () => {
    const m = detect("replit");
    expect(m.model).toBe("gpt-4o");
    expect(m.confidence).toBe(60);
  });

  it("claude-code → claude-opus-4-8 (conf 70)", () => {
    const m = detect("claude-code");
    expect(m.model).toBe("claude-opus-4-8");
    expect(m.confidence).toBe(70);
  });

  it("base44 → gemini-3.1-pro (conf 65)", () => {
    const m = detect("base44");
    expect(m.model).toBe("gemini-3.1-pro");
    expect(m.confidence).toBe(65);
  });

  it("unknown → model null, confidence 0", () => {
    const m = inferModel({ platform: "unknown", confidence: 0, signals: [] });
    expect(m.model).toBeNull();
    expect(m.confidence).toBe(0);
  });

  it("low-confidence platform detection scales model confidence down", () => {
    // Platform only 50% sure → model confidence should scale
    const m = detect("lovable", 50);
    expect(m.confidence).toBeLessThan(80);
    expect(m.confidence).toBeGreaterThan(0);
  });
});

// ── Ratio — null safety and heuristics ───────────────────────────────────────

describe("computeAiRatio", () => {
  it("returns null (not 0, not a guess) when gitCommits is null", () => {
    const result = computeAiRatio(null);
    expect(result).toBeNull();
  });

  it("returns null for empty commit list", () => {
    expect(computeAiRatio([])).toBeNull();
  });

  it("classifies conventional-commit messages with large diffs as AI", () => {
    const largeAiDiff = "diff --git a/1\n".repeat(25);
    const commits: GitCommit[] = [
      { hash: "abc1234", message: "feat: Add user authentication system", diff: largeAiDiff },
      { hash: "abc1235", message: "feat(auth): Implement OAuth provider", diff: largeAiDiff },
      { hash: "abc1236", message: "Create UserProfile component", diff: largeAiDiff },
    ];
    const ratio = computeAiRatio(commits);
    expect(ratio).not.toBeNull();
    expect(ratio!.likelyAiCommits).toBeGreaterThan(ratio!.likelyHumanCommits);
    expect(ratio!.aiRatio).toBeGreaterThan(0.5);
  });

  it("classifies issue-referenced focused commits as human", () => {
    const smallDiff = "diff --git a/auth.ts\n".repeat(2);
    const commits: GitCommit[] = [
      { hash: "abc1234", message: "Fix broken redirect after OAuth (#234)", diff: smallDiff },
      { hash: "abc1235", message: "wip: debugging token refresh issue", diff: smallDiff },
      { hash: "abc1236", message: "squash: cleanup oops", diff: smallDiff },
    ];
    const ratio = computeAiRatio(commits);
    expect(ratio).not.toBeNull();
    expect(ratio!.likelyHumanCommits).toBeGreaterThan(ratio!.likelyAiCommits);
    expect(ratio!.aiRatio).toBeLessThan(0.5);
  });

  it("aiRatio is in [0, 1]", () => {
    const commits: GitCommit[] = [
      { hash: "a", message: "feat: Add dashboard", diff: "diff --git".repeat(25) },
      { hash: "b", message: "fix bug #99", diff: "" },
    ];
    const ratio = computeAiRatio(commits);
    expect(ratio!.aiRatio).toBeGreaterThanOrEqual(0);
    expect(ratio!.aiRatio).toBeLessThanOrEqual(1);
  });

  it("totalAnalyzed reflects the full commit list (including ambiguous)", () => {
    const commits: GitCommit[] = Array.from({ length: 10 }, (_, i) => ({
      hash: `${i}`,
      message: `Commit ${i}`,  // generic — could go either way
      diff: "",
    }));
    const ratio = computeAiRatio(commits);
    expect(ratio!.totalAnalyzed).toBe(10);
  });
});

