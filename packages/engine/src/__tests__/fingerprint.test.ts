// ── Inline CodeProfile tests (no I/O) ────────────────────────────────────────

describe("detectPlatform — inline profiles, no I/O", () => {
  function makeProfile(files: string[], deps: Record<string, string> = {}): CodeProfile {
    return {
      root: "/project",
      files: files.map(p => ({ path: p, ext: "." + (p.split(".").pop() ?? ""), size: 10, lines: 1, content: "" })),
      packageJson: null,
      dependencies: deps,
      tsConfig: null,
      supabaseMigrations: [],
      apiRoutes: [],
      components: [],
      testFiles: [],
      configFiles: {},
      envExample: null,
      gitCommits: null,
      framework: "unknown",
      hasAuth: false,
      hasDatabase: false,
      hasPayments: false,
      hasUserData: false,
    };
  }

  it("replit.nix alone → replit", () => {
    expect(detectPlatform(makeProfile(["replit.nix"])).platform).toBe("replit");
  });

  it(".bolt/ child file → bolt", () => {
    expect(detectPlatform(makeProfile([".bolt/config.json"])).platform).toBe("bolt");
  });

  it(".cursorrules + .cursor/ → cursor with highest confidence", () => {
    const d = detectPlatform(makeProfile([".cursorrules", ".cursor/rules.json"]));
    expect(d.platform).toBe("cursor");
    expect(d.confidence).toBe(95); // 2 signals → 95
  });

  it("random files with no platform markers → unknown", () => {
    const d = detectPlatform(makeProfile(["src/index.ts", "package.json", "README.md"]));
    expect(d.platform).toBe("unknown");
    expect(d.signals).toHaveLength(0);
  });
});
