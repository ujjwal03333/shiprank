// ── fixture helpers ───────────────────────────────────────────────────────────

const FIXTURE_ROOT = join(tmpdir(), "shiprank-fingerprint-fixtures");

function ensureDir(d: string) { mkdirSync(d, { recursive: true }); }
function writeText(p: string, t: string) { writeFileSync(p, t, "utf8"); }
function writeJson(p: string, d: unknown) { writeFileSync(p, JSON.stringify(d, null, 2), "utf8"); }

beforeAll(() => {
  rmSync(FIXTURE_ROOT, { recursive: true, force: true });

  // ── cursor ────────────────────────────────────────────────────────────────
  const cursor = join(FIXTURE_ROOT, "cursor-app");
  ensureDir(cursor);
  writeText(join(cursor, ".cursorrules"), "You are an expert TypeScript engineer.\nFollow Next.js best practices.");
  writeJson(join(cursor, "package.json"), { name: "cursor-app", dependencies: { next: "14.2.0" } });

  // ── bolt ──────────────────────────────────────────────────────────────────
  const bolt = join(FIXTURE_ROOT, "bolt-app");
  ensureDir(join(bolt, ".bolt"));
  writeJson(join(bolt, ".bolt", "config.json"), { version: 1 });
  writeJson(join(bolt, "package.json"), { name: "bolt-app", dependencies: { react: "18.3.0" } });

  // ── lovable ───────────────────────────────────────────────────────────────
  const lovable = join(FIXTURE_ROOT, "lovable-app");
  ensureDir(lovable);
  writeText(join(lovable, "lovable.config.ts"), "export default { projectId: 'abc123' };");
  writeJson(join(lovable, "package.json"), { name: "lovable-app", devDependencies: { "lovable-tagger": "1.0.0" } });

  // ── replit ────────────────────────────────────────────────────────────────
  const replit = join(FIXTURE_ROOT, "replit-app");
  ensureDir(replit);
  writeText(join(replit, ".replit"), '[run]\ncommand = "node index.js"\n');
  writeJson(join(replit, "package.json"), { name: "replit-app", dependencies: { express: "4.19.0" } });

  // ── v0 ────────────────────────────────────────────────────────────────────
  const v0 = join(FIXTURE_ROOT, "v0-app");
  ensureDir(join(v0, "components"));
  writeText(join(v0, "v0.config.ts"), "export default { registry: 'registry.v0.dev' };");
  writeJson(join(v0, "package.json"), { name: "v0-app", dependencies: { next: "14.2.0" } });
  // Also add a component with the Generated-by comment to test multi-signal boost
  writeText(join(v0, "components", "Hero.tsx"), "// Generated by v0\nexport function Hero() { return <div /> }");

  // ── base44 ────────────────────────────────────────────────────────────────
  const base44 = join(FIXTURE_ROOT, "base44-app");
  ensureDir(base44);
  writeJson(join(base44, "base44.json"), { version: "1.0.0", appId: "xyz" });
  writeJson(join(base44, "package.json"), { name: "base44-app", dependencies: { "@base44/sdk": "2.0.0" } });

  // ── claude-code ───────────────────────────────────────────────────────────
  const cc = join(FIXTURE_ROOT, "claude-code-app");
  ensureDir(join(cc, ".claude"));
  writeJson(join(cc, ".claude", "settings.json"), { permissions: [] });
  writeText(join(cc, "CLAUDE.md"), "# Project\nThis is a Claude Code project.");
  writeJson(join(cc, "package.json"), { name: "claude-code-app", dependencies: { next: "14.2.0" } });

  // ── unknown ───────────────────────────────────────────────────────────────
  const unknown = join(FIXTURE_ROOT, "unknown-app");
  ensureDir(unknown);
  writeJson(join(unknown, "package.json"), { name: "unknown-app", dependencies: { react: "18.3.0" } });
});

afterAll(() => {
  rmSync(FIXTURE_ROOT, { recursive: true, force: true });
});

